-- V1: a estrutura inicial do carrinho

create table carrinho (
                          id               bigint generated by default as identity primary key,
                          cliente_id       varchar(255)                not null,
                          status           varchar(255)                not null,
                          atualizado_em    timestamp(6) with time zone not null,
                          lembrete_enviado boolean                     not null
);

create index idx_carrinho_status_atualizado on carrinho (status, atualizado_em);

create table item_carrinho (
                               id             bigint generated by default as identity primary key,
                               carrinho_id    bigint         not null references carrinho (id),
                               produto        varchar(255)   not null,
                               quantidade     integer        not null,
                               preco_unitario numeric(10, 2) not null
);

create table lembrete (
                          id          bigint generated by default as identity primary key,
                          carrinho_id bigint                      not null,
                          cliente_id  varchar(255)                not null,
                          instancia   varchar(255)                not null,
                          enviado_em  timestamp(6) with time zone not null
);